//! Diagnostic catalog generator.
//!
//! Reads the pinned TypeScript `diagnosticMessages.json` and renders
//! `crates/bamts-compiler/src/generated/diagnostic_messages.rs`.

use std::{
    collections::BTreeMap,
    fmt::{self, Write as _},
    fs, io,
    path::Path,
};

#[derive(Debug)]
pub enum CatalogError {
    Io(io::Error),
    Json(serde_json::Error),
    Mismatch { path: String },
}

impl From<io::Error> for CatalogError {
    fn from(err: io::Error) -> Self {
        Self::Io(err)
    }
}

impl From<serde_json::Error> for CatalogError {
    fn from(err: serde_json::Error) -> Self {
        Self::Json(err)
    }
}

impl fmt::Display for CatalogError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Io(err) => write!(f, "I/O error: {err}"),
            Self::Json(err) => write!(f, "JSON error: {err}"),
            Self::Mismatch { path } => write!(f, "generated file does not match: {path}"),
        }
    }
}

impl std::error::Error for CatalogError {}

#[derive(Debug, serde::Deserialize, Clone)]
struct RawEntry {
    category: String,
    code: u32,
}

