        assert_eq!(message.category(), TsCategory::Error);
        assert_eq!(message.template(), "Unterminated string literal.");
        assert_eq!(by_u32(1002), Some(message));
        assert_eq!(by_bamts_code("1002"), Some(message));
        assert_eq!(
            by_diagnostic_code(DiagnosticCode::new("1002")),
            Some(message)
        );
        let five_digit = by_u32(17000).expect("TS17000 must exist");
        assert_eq!(by_bamts_code("17000"), Some(five_digit));
        assert_eq!(by_ts_code("TS17000"), Some(five_digit));
