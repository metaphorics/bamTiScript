use crate::diagnostic::{DiagnosticCode, DiagnosticSeverity};

/// TypeScript diagnostic category.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub enum TsCategory {
    /// The diagnostic prevents the program from compiling.
    Error,
    /// The diagnostic is non-fatal.
    Warning,
    /// The compiler suggests an optional improvement.
    Suggestion,
    /// The diagnostic is informational only.
    Message,
}

impl TsCategory {
    /// Maps the TypeScript category to the compiler's `DiagnosticSeverity`.
    #[must_use]
    pub const fn to_diagnostic_severity(self) -> DiagnosticSeverity {
        match self {
            Self::Error => DiagnosticSeverity::Error,
            // Suggestions and messages are rendered as non-fatal warnings.
            Self::Warning | Self::Suggestion | Self::Message => DiagnosticSeverity::Warning,
        }
    }
}

/// Failure while instantiating a diagnostic template.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum FormatError {
    /// The number of arguments does not match the template.
    ArityMismatch { expected: usize, got: usize },
    /// A placeholder index was not within the expected range.
    BadPlaceholder { index: usize, max: usize },
}

impl std::fmt::Display for FormatError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::ArityMismatch { expected, got } => {
                write!(f, "expected {expected} arguments, got {got}")
            }
            Self::BadPlaceholder { index, max } => {
                write!(f, "placeholder index {index} out of range (max {max})")
            }
        }
    }
}

impl std::error::Error for FormatError {}

/// Strongly-typed substitution list for a diagnostic template.
///
/// The const generic `N` is the number of supplied arguments. This is checked
/// against the template's placeholder count at format time.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Args<'a, const N: usize>([&'a str; N]);

impl<'a, const N: usize> Args<'a, N> {
    /// Wraps the argument array.
    #[must_use]
    pub const fn new(args: [&'a str; N]) -> Self {
        Self(args)
    }
}

/// One generated diagnostic message with its code, category, and template.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct DiagnosticMessage {
    code: u32,
    bamts_code: &'static str,
    ts_code: &'static str,
    category: TsCategory,
    template: &'static str,
    arity: u8,
}

impl DiagnosticMessage {
    /// The numeric diagnostic code.
    #[must_use]
    pub const fn code(&self) -> u32 {
        self.code
    }

    /// The BAMTS code string (the numeric code).
    #[must_use]
    pub const fn bamts_code(&self) -> &'static str {
        self.bamts_code
    }

    /// The canonical TypeScript `TSxxxx` label.
    #[must_use]
    pub const fn ts_code(&self) -> &'static str {
        self.ts_code
    }

    /// The diagnostic category.
    #[must_use]
    pub const fn category(&self) -> TsCategory {
        self.category
    }

    /// The message template, possibly containing `{0}`-style placeholders.
    #[must_use]
    pub const fn template(&self) -> &'static str {
        self.template
    }

    /// The number of arguments required by the template.
    #[must_use]
    pub const fn arity(&self) -> u8 {
        self.arity
    }

    /// The stable `DiagnosticCode` identity.
    #[must_use]
    pub const fn diagnostic_code(&self) -> DiagnosticCode {
        DiagnosticCode::new(self.bamts_code)
    }

    /// Renders the template with the supplied checked arguments.
    pub fn format<'a, const N: usize>(&self, args: Args<'a, N>) -> Result<String, FormatError> {
        if N != self.arity as usize {
            return Err(FormatError::ArityMismatch {
                expected: self.arity as usize,
                got: N,
            });
        }
        let mut out = String::new();
        let mut chars = self.template.chars().peekable();
        while let Some(ch) = chars.next() {
            if ch == '{' {
                let mut digits = String::new();
                while let Some(&next) = chars.peek() {
                    if next.is_ascii_digit() {
                        digits.push(next);
                        chars.next();
                    } else {
                        break;
                    }
                }
                if !digits.is_empty() && chars.peek() == Some(&'}') {
                    chars.next();
                    let index = digits.parse::<usize>().unwrap();
                    if index >= N {
                        return Err(FormatError::BadPlaceholder {
                            index,
                            max: N.saturating_sub(1),
                        });
                    }
                    out.push_str(args.0[index]);
                } else {
                    out.push(ch);
                    out.push_str(&digits);
                }
            } else {
                out.push(ch);
            }
        }
        Ok(out)
    }
}

/// Number of catalog entries.
pub const CATALOG_LEN: usize = __CATALOG_LEN__;

/// Stable, sorted, unique catalog of TypeScript diagnostic messages.
#[rustfmt::skip]
pub static CATALOG: [DiagnosticMessage; CATALOG_LEN] = [
__CATALOG__
];

/// Looks up a message by its numeric code.
#[must_use]
pub fn by_u32(code: u32) -> Option<&'static DiagnosticMessage> {
    CATALOG
        .as_slice()
        .binary_search_by(|message| message.code.cmp(&code))
        .ok()
        .map(|index| &CATALOG[index])
}

/// Looks up a message by its BAMTS code string.
#[must_use]
pub fn by_bamts_code(code: &str) -> Option<&'static DiagnosticMessage> {
    code.parse::<u32>().ok().and_then(by_u32)
}

/// Looks up a message by its TypeScript `TSxxxx` label.
#[must_use]
pub fn by_ts_code(ts_code: &str) -> Option<&'static DiagnosticMessage> {
    ts_code
        .strip_prefix("TS")?
        .parse::<u32>()
        .ok()
        .and_then(by_u32)
}

/// Looks up a message by a `DiagnosticCode`.
#[must_use]
pub fn by_diagnostic_code(code: DiagnosticCode) -> Option<&'static DiagnosticMessage> {
    by_bamts_code(code.as_str())
}

/// Returns the whole catalog for deterministic iteration.
#[must_use]
pub fn all() -> &'static [DiagnosticMessage] {
    &CATALOG
}

/// Renders a BAMTS code as its `TSxxxx` label when it is a numeric TS code.
#[must_use]
pub fn ts_code_for(code: &str) -> String {
    if !code.is_empty() && code.chars().all(|ch| ch.is_ascii_digit()) {
        format!("TS{code}")
    } else {
        code.to_owned()
    }
}

/// Returns the precomputed TS label for a known catalog entry.
#[must_use]
pub fn ts_code_for_diagnostic(code: DiagnosticCode) -> Option<&'static str> {
    by_diagnostic_code(code).map(|message| message.ts_code())
}

